static auto IsIdentifierStart(char c) noexcept -> bool
{
    FO_NO_STACK_TRACE_ENTRY();

    return std::isalpha(static_cast<unsigned char>(c)) != 0 || c == '_';
}

static auto IsIdentifierPart(char c) noexcept -> bool
{
    FO_NO_STACK_TRACE_ENTRY();

    return std::isalnum(static_cast<unsigned char>(c)) != 0 || c == '_';
}

static auto EscapeCsIdentifier(string_view name) -> string
{
    FO_STACK_TRACE_ENTRY();

    string result;
    result.reserve(name.size() + 1);

    for (char c : name) {
        result.push_back(IsIdentifierPart(c) ? c : '_');
    }

    if (result.empty() || !IsIdentifierStart(result.front())) {
        result.insert(result.begin(), '_');
    }

    if (IsCsKeyword(result)) {
        result.insert(result.begin(), '@');
    }

    return result;
}

static auto MakeUniqueCsIdentifier(string_view name, unordered_set<string>& used_names) -> string
{
    FO_STACK_TRACE_ENTRY();

    string result = EscapeCsIdentifier(name);

    if (used_names.emplace(result).second) {
        return result;
    }

    for (int32_t suffix = 2;; suffix++) {
        string candidate = strex("{}{}", result, suffix).str();

        if (used_names.emplace(candidate).second) {
            return candidate;
        }
    }
}

static auto EscapeXml(string_view value) -> string
{
    FO_STACK_TRACE_ENTRY();

    string result;
    result.reserve(value.size());

    for (char c : value) {
        switch (c) {
        case '&':
            result += "&amp;";
            break;
        case '<':
            result += "&lt;";
            break;
        case '>':
            result += "&gt;";
            break;
        case '"':
            result += "&quot;";
            break;
        case '\'':
            result += "&apos;";
            break;
        default:
            result.push_back(c);
            break;
        }
    }

    return result;
}

static auto EscapeCsStringLiteral(string_view value) -> string
{
    FO_STACK_TRACE_ENTRY();

    string result;
    result.reserve(value.size());

    for (char c : value) {
        if (c == '\\' || c == '"') {
            result.push_back('\\');
        }

        result.push_back(c);
    }

    return result;
}

static auto TrimString(string value) -> string
{
    FO_STACK_TRACE_ENTRY();

    auto is_space = [](char c) { return std::isspace(static_cast<unsigned char>(c)) != 0; };
    value.erase(value.begin(), std::find_if_not(value.begin(), value.end(), is_space));
    value.erase(std::find_if_not(value.rbegin(), value.rend(), is_space).base(), value.end());
    return value;
}

static auto ScopeMatches(string_view scope, string_view value) -> bool
{
    FO_STACK_TRACE_ENTRY();

    string lower_scope = strex(scope).lower().str();
    return scope.empty() || scope == "*" || lower_scope == "all" || scope == value;
}

static auto CollectScopedValues(const vector<string>& entries, string_view assembly_name, string_view target_name) -> vector<string>
{
    FO_STACK_TRACE_ENTRY();

    vector<string> result;

    for (const string& raw_entry : entries) {
        string entry = TrimString(raw_entry);

        if (entry.empty()) {
            continue;
        }

        size_t assembly_sep = entry.find(',');
        size_t target_sep = assembly_sep != string::npos ? entry.find(',', assembly_sep + 1) : string::npos;

        if (assembly_sep == string::npos || target_sep == string::npos) {
            result.emplace_back(std::move(entry));
            continue;
        }

        string entry_assembly = TrimString(entry.substr(0, assembly_sep));
        string entry_target = TrimString(entry.substr(assembly_sep + 1, target_sep - assembly_sep - 1));
        string entry_value = TrimString(entry.substr(target_sep + 1));

        if (!entry_value.empty() && ScopeMatches(entry_assembly, assembly_name) && ScopeMatches(entry_target, target_name)) {
            result.emplace_back(std::move(entry_value));
        }
    }

    return result;
}

