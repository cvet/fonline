{
    FO_NO_STACK_TRACE_ENTRY();

    return property_name == "Name" || property_name == "Id" || property_name == "ProtoId" || property_name == "IsDestroyed" || property_name == "IsDestroying";
}

static void AppendProperty(ostringstream& out, const string& type_name, const string& property_name, bool writable, bool is_static, bool shadows_entity_base, unordered_set<string>& member_names, optional<string_view> initializer = std::nullopt, bool is_ref_type = false)
{
    FO_STACK_TRACE_ENTRY();

    if (!member_names.emplace(property_name).second) {
        return;
    }

    out << CS_INDENT << "public ";

    if (is_static) {
        out << "static ";
    }
    if (shadows_entity_base && IsEntityBaseShadowName(property_name)) {
        out << "new ";
    }

    out << type_name << " " << property_name << "\n";
    out << CS_INDENT << "{\n";
    out << CS_INDENT << "    get;\n";

    if (writable) {
        out << CS_INDENT << "    set;\n";
    }

    out << CS_INDENT << "}";

    if (optional<string> property_initializer = MakePropertyInitializer(type_name, initializer, is_ref_type); property_initializer.has_value()) {
        out << " = " << *property_initializer << ";";
    }

    out << "\n\n";
}

static void AppendNativeProperty(ostringstream& out, ptr<const Property> prop, bool is_static, bool shadows_entity_base, unordered_set<string>& member_names)
{
    FO_STACK_TRACE_ENTRY();

    string type_name = MakeCsPropertyTypeName(prop);
    string decl_type = prop->IsNullable() ? type_name + "?" : type_name;
    string property_name = EscapeCsIdentifier(prop->GetNameWithoutComponent());
    const BaseTypeDesc& base_type = prop->GetBaseType();
    bool use_scalar_bridge = !prop->IsNullable() && !prop->IsArray() && !prop->IsDict() && IsManagedAbiFixedPropertyValue(base_type);
    bool use_array_bridge = !prop->IsNullable() && prop->IsArray() && !prop->IsDict() && IsManagedAbiFixedPropertyValue(base_type);
    bool use_integer_bridge = use_scalar_bridge && !is_static && (base_type.IsInt8 || base_type.IsUInt8 || base_type.IsInt16 || base_type.IsUInt16);

    if (!member_names.emplace(property_name).second) {
        return;
    }

    string entity_ptr = string {MakeTargetPtrExpression(is_static, false)};

    out << CS_INDENT << "public ";

    if (is_static) {
        out << "static ";
    }
    if (shadows_entity_base && IsEntityBaseShadowName(property_name)) {
        out << "new ";
    }

    out << decl_type << " " << property_name << "\n";
    out << CS_INDENT << "{\n";
    out << CS_INDENT << "    get\n";
    out << CS_INDENT << "    {\n";

    if (use_integer_bridge) {
        out << CS_INDENT << "        return (" << decl_type << ")global::FOnline.Native.GetEntityValueAsInt(" << entity_ptr << ", " << prop->GetRegIndex() << ");\n";
    }
    else if (use_scalar_bridge) {
        out << CS_INDENT << "        return global::FOnline.Native.GetPropertyValue<" << decl_type << ">(" << entity_ptr << ", " << prop->GetRegIndex() << ");\n";
    }
    else if (use_array_bridge) {
        out << CS_INDENT << "        return global::FOnline.Native.GetPropertyList<" << MakeCsTypeName(base_type) << ">(" << entity_ptr << ", " << prop->GetRegIndex() << ");\n";
    }
    else {
        out << CS_INDENT << "        return (" << decl_type << ")global::FOnline.Native.GetProperty(" << entity_ptr << ", " << prop->GetRegIndex() << ");\n";
    }

    out << CS_INDENT << "    }\n";

    if (prop->IsMutable()) {
        out << CS_INDENT << "    set\n";
        out << CS_INDENT << "    {\n";

        if (use_integer_bridge) {
            out << CS_INDENT << "        global::FOnline.Native.SetEntityValueAsInt(" << entity_ptr << ", " << prop->GetRegIndex() << ", value);\n";
        }
        else if (use_scalar_bridge) {
            out << CS_INDENT << "        global::FOnline.Native.SetPropertyValue<" << decl_type << ">(" << entity_ptr << ", " << prop->GetRegIndex() << ", value);\n";
        }
        else if (use_array_bridge) {
            out << CS_INDENT << "        global::FOnline.Native.SetPropertyList<" << MakeCsTypeName(base_type) << ">(" << entity_ptr << ", " << prop->GetRegIndex() << ", value);\n";
        }
        else {
            out << CS_INDENT << "        global::FOnline.Native.SetProperty(" << entity_ptr << ", " << prop->GetRegIndex() << ", value);\n";
        }

        out << CS_INDENT << "    }\n";
    }

    out << CS_INDENT << "}\n\n";
}

static void AppendSettingProperty(ostringstream& out, string_view indent, const ComplexTypeDesc& type, const string& property_name, string_view setting_name, unordered_set<string>& member_names, nptr<const ManagedAbiSettingEntry> abi_setting)
{
    FO_STACK_TRACE_ENTRY();

    if (!member_names.emplace(property_name).second) {
        return;
    }

    // A setting is read on the script surface and never written: a configured value is a knob someone
    // turned, and a value that changes while the game runs belongs to the system that owns it
    string setting_literal = EscapeCsStringLiteral(setting_name);
    string type_name = MakeCsTypeName(type);
    const BaseTypeDesc& base_type = type.BaseType;
    string getter_method;
    string getter_cast;

    if (type.Kind == ComplexTypeKind::Simple) {
        if (base_type.IsBool) {
            getter_method = "GetSettingBool";
        }
        else if (base_type.IsEnum) {
            getter_method = "GetSettingInt";
            getter_cast = strex("({})", type_name).str();
        }
        else if (base_type.IsInt8 || base_type.IsInt16 || base_type.IsInt32) {
            getter_method = "GetSettingInt";
            getter_cast = strex("({})", type_name).str();
        }
        else if (base_type.IsUInt8 || base_type.IsUInt16 || base_type.IsUInt32) {
            getter_method = "GetSettingUInt";
            getter_cast = strex("({})", type_name).str();
        }
        else if (base_type.IsInt64) {
            getter_method = "GetSettingLong";
        }
        else if (base_type.IsUInt64) {
            getter_method = "GetSettingULong";
        }
        else if (base_type.IsSingleFloat) {
            getter_method = "GetSettingFloat";
        }
        else if (base_type.IsDoubleFloat) {
            getter_method = "GetSettingDouble";
        }
        else if (base_type.IsString) {
            getter_method = "GetSettingString";
        }
        else {
            throw ManagedScriptBakerException("Unsupported Managed setting type", strex("{} {}", setting_name, base_type.Name).str());
        }
    }
    else if (type.Kind == ComplexTypeKind::Array) {
        if (base_type.IsBool) {
            getter_method = "GetSettingBoolList";
        }
        else if (base_type.IsInt8) {
            getter_method = "GetSettingSByteList";
        }
        else if (base_type.IsUInt8) {
            getter_method = "GetSettingByteList";
        }
        else if (base_type.IsInt16) {
            getter_method = "GetSettingShortList";
        }
        else if (base_type.IsUInt16) {
            getter_method = "GetSettingUShortList";
        }
        else if (base_type.IsInt32) {
            getter_method = "GetSettingIntList";
        }
        else if (base_type.IsUInt32) {
            getter_method = "GetSettingUIntList";
        }
        else if (base_type.IsInt64) {
            getter_method = "GetSettingLongList";
        }
        else if (base_type.IsUInt64) {
            getter_method = "GetSettingULongList";
        }
        else if (base_type.IsSingleFloat) {
            getter_method = "GetSettingFloatList";
        }
        else if (base_type.IsDoubleFloat) {
            getter_method = "GetSettingDoubleList";
        }
        else if (base_type.IsString) {
            getter_method = "GetSettingStringList";
        }
        else {
            throw ManagedScriptBakerException("Unsupported Managed array setting type", strex("{} {}", setting_name, base_type.Name).str());
        }
    }
    else {
        throw ManagedScriptBakerException("Unsupported Managed setting type", strex("{} {}", setting_name, type_name).str());
    }

    out << indent << "public static " << type_name << " " << property_name << "\n";
    out << indent << "{\n";
    out << indent << "    get\n";
    out << indent << "    {\n";

    if (abi_setting && abi_setting->UsesTypedBridge) {
        out << indent << "        return global::FOnline.Native.GetSettingValue<" << type_name << ">(" << abi_setting->Id << ");\n";
    }
    else {
        out << indent << "        return " << getter_cast << "global::FOnline.Native." << getter_method << "(\n";
        out << indent << "            \"" << setting_literal << "\");\n";
    }

    out << indent << "    }\n";
    out << indent << "}\n\n";
}

static void AppendMethod(ostringstream& out, const MethodDesc& method, size_t method_index, string_view owner_type_name, bool is_static, bool is_ref_type_owner, bool allow_native_bridge, bool is_synced_entity_owner, const unordered_set<string>& reserved_names, unordered_set<string>& signatures, bool async_callbacks, nptr<const ManagedAbiMethodEntry> abi_method)
{
    FO_STACK_TRACE_ENTRY();

    if (method.GlobalGetter || method.Getter || method.Setter) {
        return;
    }

    string method_name = EscapeCsIdentifier(method.Name);

    if (reserved_names.count(method_name) != 0) {
        method_name += "Method";
    }

    auto arg_declarations = MakeCsArgumentDeclarations(method.Args, async_callbacks);
    string args = JoinCsCommaList(arg_declarations);
    string ret = MakeCsTypeName(method.Ret);
    string signature = strex("{}({})", method_name, args).str();

    if (!signatures.emplace(signature).second) {
        return;
    }

    bool is_method_static = is_static || (is_ref_type_owner && method.Name == "__Factory");
    string declaration_prefix = "public ";

    if (is_method_static) {
        declaration_prefix += "static ";
    }
    // Emit the nullable return annotation in the signature only; `ret` stays non-nullable for the
    // special-case logic and body emission below
    declaration_prefix += MakeCsTypeName(method.Ret, method.ReturnNullable);
    declaration_prefix += " ";

    // A server entity export reads or mutates its receiver, so the caller owns that entity's cover
    if (is_synced_entity_owner) {
        out << CS_INDENT << "[RequiresCover]\n";
    }

    // A downward accessor hands back entities that the receiver's cover already covers, so the value arrives
    // covered and discharges the obligation at the next call that takes it
    if (method.ReturnProvidesCover) {
        out << CS_INDENT << "[return: ProvidesCover]\n";
    }

    // An upward accessor hands back the receiver's parent or an ancestor, which only cover declared with that
    // reach already covers
    if (method.ReturnIsParent) {
        out << CS_INDENT << "[return: ReturnsParent]\n";
    }
    if (method.ReturnIsAncestor) {
        out << CS_INDENT << "[return: ReturnsAncestor]\n";
    }

    // The raw synchronization surface names itself, so the analyzer asks the declaration instead of holding a
    // list of method names that a rename here would quietly invalidate
    if (method.IsCoverPrimitive) {
        out << CS_INDENT << "[CoverPrimitive]\n";
    }
    if (method.IsCoverProbe) {
        out << CS_INDENT << "[CoverProbe]\n";
    }
    if (method.IsSingletonLock) {
        out << CS_INDENT << "[SingletonLock]\n";
    }

    AppendCsCallableDeclaration(out, CS_INDENT, declaration_prefix, method_name, arg_declarations, "");

    if (is_method_static && method.Name == "Log" && method.Args.size() == 1 && ret == "void" && MakeCsTypeName(method.Args.front().Type) == "string") {
        unordered_set<string> used_arg_names;
        string arg_name = MakeUniqueCsIdentifier(method.Args.front().Name.empty() ? "arg0" : method.Args.front().Name, used_arg_names);
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    global::FOnline.Native.Log(" << arg_name << ");\n";
        out << CS_INDENT << "}\n";
    }
    else if (is_method_static && method.Name == "GetHashStr" && method.Args.size() == 1 && ret == "string" && MakeCsTypeName(method.Args.front().Type) == "ulong") {
        unordered_set<string> used_arg_names;
        string arg_name = MakeUniqueCsIdentifier(method.Args.front().Name.empty() ? "arg0" : method.Args.front().Name, used_arg_names);
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    return global::FOnline.Native.GetHashStrFromHash(" << arg_name << ");\n";
        out << CS_INDENT << "}\n";
    }
    else if (allow_native_bridge && IsManagedBridgeMethod(method)) {
        FO_VERIFY_AND_THROW(abi_method, "Managed method is missing from the ABI manifest", owner_type_name, method.Name, method_index);

        string entity_ptr = string {MakeTargetPtrExpression(is_method_static, is_ref_type_owner)};
        bool has_mutable_args = HasMutableArgs(method.Args);
        size_t mutable_args_count = CountMutableArgs(method.Args);
        string body_indent = strex("{}    ", CS_INDENT).str();

        if (abi_method->UsesScalarFrame) {
            out << CS_INDENT << "{\n";
            AppendIndexedMethodCall(out, body_indent, *abi_method, entity_ptr, method.Args, ret);
            out << CS_INDENT << "}\n";
        }
        else if (has_mutable_args) {
            out << CS_INDENT << "{\n";
            AppendObjectArrayDeclaration(out, body_indent, "__args", method.Args);
            out << "\n";

            if (ret == "void" && mutable_args_count == 1) {
                AppendNativeCallMethodExpression(out, body_indent, "object __result = ", abi_method->Id, entity_ptr, "__args", ";");
                AppendSingleMutableArgAssignment(out, method.Args, "__result");
            }
            else {
                AppendNativeCallMethodExpression(out, body_indent, "object[] __result = (object[])", abi_method->Id, entity_ptr, "__args", ";");

                if (ret == "void") {
                    AppendMutableArgAssignments(out, method.Args, "__result", 0);
                }
                else {
                    AppendMutableArgAssignments(out, method.Args, "__result", 1);
                    out << CS_INDENT << "    return (" << ret << ")__result[0];\n";
                }
            }

            out << CS_INDENT << "}\n";
        }
        else if (ret == "void") {
            out << CS_INDENT << "{\n";
            AppendObjectArrayDeclaration(out, body_indent, "__args", method.Args);
            out << "\n";
            AppendNativeCallMethodExpression(out, body_indent, "", abi_method->Id, entity_ptr, "__args", ";");
            out << CS_INDENT << "}\n";
        }
        else {
            out << CS_INDENT << "{\n";
            AppendObjectArrayDeclaration(out, body_indent, "__args", method.Args);
            out << "\n";
            AppendNativeCallMethodExpression(out, body_indent, "object __result = ", abi_method->Id, entity_ptr, "__args", ";");
            out << CS_INDENT << "    return (" << ret << ")__result;\n";
            out << CS_INDENT << "}\n";
        }
    }
    else {
        throw ManagedScriptBakerException("Unsupported Managed API method", strex("{}.{}", owner_type_name, method.Name).str());
    }

    out << "\n";
}

static auto HasMethodSignature(const vector<MethodDesc>& methods, string_view method_name, string_view ret, std::initializer_list<string_view> arg_types) -> bool
{
    FO_STACK_TRACE_ENTRY();

    for (const MethodDesc& method : methods) {
        if (method.GlobalGetter || method.Getter || method.Setter) {
            continue;
        }
        if (method.Name != method_name) {
            continue;
        }
        if (MakeCsTypeName(method.Ret) != ret) {
            continue;
        }
        if (method.Args.size() != arg_types.size()) {
            continue;
        }

        bool matched = true;
        size_t arg_index = 0;

        for (string_view arg_type : arg_types) {
            if (MakeCsTypeName(method.Args[arg_index].Type) != arg_type) {
                matched = false;
                break;
            }

            arg_index++;
        }

        if (matched) {
            return true;
        }
    }

    return false;
}

static void AppendMethodProperties(ostringstream& out, const vector<MethodDesc>& methods, string_view owner_type_name, bool is_static, bool is_ref_type_owner, bool allow_native_bridge, unordered_set<string>& member_names, const ManagedAbiManifest& abi)
{
    FO_STACK_TRACE_ENTRY();

    struct MethodAccessors
    {
        nptr<const MethodDesc> Getter {};
        nptr<const MethodDesc> Setter {};
        size_t GetterIndex {};
        size_t SetterIndex {};
    };

    map<string, MethodAccessors> accessor_map;

    for (size_t method_index = 0; method_index < methods.size(); method_index++) {
        const MethodDesc& method = methods[method_index];

        if (method.GlobalGetter || method.Getter || method.Setter) {
            MethodAccessors& accessors = accessor_map[method.Name];

            if (method.GlobalGetter || method.Getter) {
                accessors.Getter = &method;
                accessors.GetterIndex = method_index;
            }
            if (method.Setter) {
                accessors.Setter = &method;
                accessors.SetterIndex = method_index;
            }
        }
    }

    string entity_ptr = string {MakeTargetPtrExpression(is_static, is_ref_type_owner)};
    string body_indent = strex("{}        ", CS_INDENT).str();

    for (const auto& [method_name_raw, accessors] : accessor_map) {
        string property_name = EscapeCsIdentifier(method_name_raw);

        if (member_names.count(property_name) != 0) {
            continue;
        }

        nptr<const MethodDesc> getter = accessors.Getter;
        nptr<const MethodDesc> setter = accessors.Setter;
        string property_type;
        bool ref_type_property = false;

        if (getter) {
            property_type = MakeCsTypeName(getter->Ret, getter->ReturnNullable);
            ref_type_property = IsNonNullableRefType(getter->Ret, getter->ReturnNullable);
        }
        else if (setter && !setter->Args.empty()) {
            property_type = MakeCsTypeName(setter->Args.front().Type, setter->Args.front().Nullable);
            ref_type_property = IsNonNullableRefType(setter->Args.front().Type, setter->Args.front().Nullable);
        }
        else {
            continue;
        }

        // A getter/setter is dispatched through the ABI method id, exactly like a regular method
        // (the backend resolves accessors the same way)
        bool getter_bridgeable = !getter || CanUseManagedBridge(getter->Ret);
        bool setter_bridgeable = !setter || (!setter->Args.empty() && CanUseManagedBridge(setter->Args.front().Type));
        bool emit_bridge = allow_native_bridge && getter_bridgeable && setter_bridgeable;

        member_names.emplace(property_name);

        out << CS_INDENT << "public ";

        if (is_static) {
            out << "static ";
        }

        out << property_type << " " << property_name << "\n";
        out << CS_INDENT << "{\n";

        if (!emit_bridge) {
            if (getter) {
                out << CS_INDENT << "    get;\n";
            }
            if (setter) {
                out << CS_INDENT << "    set;\n";
            }

            out << CS_INDENT << "}";

            if (optional<string> property_initializer = MakePropertyInitializer(property_type, std::nullopt, ref_type_property); property_initializer.has_value()) {
                out << " = " << *property_initializer << ";";
            }

            out << "\n\n";
            continue;
        }

        if (getter) {
            string getter_ret = MakeCsTypeName(getter->Ret);
            nptr<const ManagedAbiMethodEntry> getter_abi = FindManagedAbiMethod(abi, owner_type_name, getter->Name, accessors.GetterIndex);
            FO_VERIFY_AND_THROW(getter_abi, "Managed getter is missing from the ABI manifest", owner_type_name, getter->Name);

            out << CS_INDENT << "    get\n";
            out << CS_INDENT << "    {\n";

            if (getter_abi->UsesScalarFrame) {
                AppendIndexedMethodCall(out, body_indent, *getter_abi, entity_ptr, getter->Args, getter_ret);
            }
            else {
                AppendObjectArrayDeclaration(out, body_indent, "__args", getter->Args);
                out << "\n";
                AppendNativeCallMethodExpression(out, body_indent, "object __result = ", getter_abi->Id, entity_ptr, "__args", ";");
                out << body_indent << "return (" << getter_ret << ")__result;\n";
            }

            out << CS_INDENT << "    }\n";
        }

        if (setter) {
            nptr<const ManagedAbiMethodEntry> setter_abi = FindManagedAbiMethod(abi, owner_type_name, setter->Name, accessors.SetterIndex);
            FO_VERIFY_AND_THROW(setter_abi, "Managed setter is missing from the ABI manifest", owner_type_name, setter->Name);

            out << CS_INDENT << "    set\n";
            out << CS_INDENT << "    {\n";

            if (setter_abi->UsesScalarFrame) {
                FO_VERIFY_AND_THROW(!setter_abi->Args.empty(), "Managed scalar setter has no argument slot", owner_type_name, setter->Name);
                out << body_indent << "global::FOnline.ScalarCallFrame __frame = default;\n";
                out << body_indent << "global::System.Runtime.CompilerServices.Unsafe.WriteUnaligned(ref __frame[" << setter_abi->Args[0].Offset << "], " << MakeCsFrameValueExpression(setter_abi->Args[0], setter->Args.front().Type, "value") << ");\n";
                out << body_indent << "global::FOnline.Native.CallMethodIndexed(" << setter_abi->Id << ", " << entity_ptr << ", ref __frame[0], " << setter_abi->FrameSize << ");\n";
            }
            else {
                out << body_indent << "object?[] __args = new object?[] { value };\n";
                out << "\n";
                AppendNativeCallMethodExpression(out, body_indent, "", setter_abi->Id, entity_ptr, "__args", ";");
            }

            out << CS_INDENT << "    }\n";
        }

        out << CS_INDENT << "}\n\n";
    }
}

static void AppendMethods(ostringstream& out, const vector<MethodDesc>& methods, string_view owner_type_name, bool is_static, bool is_ref_type_owner, bool allow_native_bridge, bool is_synced_entity_owner, unordered_set<string>& member_names, const ManagedAbiManifest& abi)
{
    FO_STACK_TRACE_ENTRY();

    unordered_set<string> signatures;

    AppendMethodProperties(out, methods, owner_type_name, is_static, is_ref_type_owner, allow_native_bridge, member_names, abi);

    for (size_t method_index = 0; method_index < methods.size(); method_index++) {
        const MethodDesc& method = methods[method_index];
        nptr<const ManagedAbiMethodEntry> abi_method = FindManagedAbiMethod(abi, owner_type_name, method.Name, method_index);
        AppendMethod(out, method, method_index, owner_type_name, is_static, is_ref_type_owner, allow_native_bridge, is_synced_entity_owner, member_names, signatures, false, abi_method);
        bool is_timer_method = method.Name == "StartTimeEvent" || method.Name == "CountTimeEvent" || method.Name == "StopTimeEvent" || method.Name == "RepeatTimeEvent" || method.Name == "SetTimeEventData";

        if (is_timer_method && std::ranges::any_of(method.Args, [](const ArgDesc& arg) { return arg.Type.Kind == ComplexTypeKind::Callback && arg.Type.CallbackArgs && !arg.Type.CallbackArgs->empty() && !arg.Type.CallbackArgs->front(); })) {
            AppendMethod(out, method, method_index, owner_type_name, is_static, is_ref_type_owner, allow_native_bridge, is_synced_entity_owner, member_names, signatures, true, abi_method);
        }
    }
}

static void AppendDynamicRefTypeProperties(ostringstream& out, ptr<const PropertyRegistrar> registrar, string_view owner_type_name, unordered_set<string>& member_names)
{
    FO_STACK_TRACE_ENTRY();

    for (size_t i = 1; i < registrar->GetPropertiesCount(); i++) {
        auto prop = registrar->GetPropertyByIndexUnsafe(i);

        if (prop->IsDisabled()) {
            continue;
        }

        string prop_type = MakeCsPropertyTypeName(prop);

        if (prop->IsNullable()) {
            prop_type += "?";
        }

        string raw_prop_name = MakeManagedDynamicRefTypePropertyName(prop);
        string prop_name = EscapeCsIdentifier(raw_prop_name);
        FO_VERIFY_AND_THROW(!member_names.contains(prop_name), "Managed dynamic RefType property name collision", owner_type_name, prop->GetName(), raw_prop_name);
        bool ref_type_property = !prop->IsNullable() && !prop->IsDict() && !prop->IsArray() && prop->GetBaseType().IsRefType;
        AppendProperty(out, prop_type, prop_name, true, false, false, member_names, std::nullopt, ref_type_property);
    }
}

static void AppendEntityProperties(ostringstream& out, ptr<const PropertyRegistrar> registrar, string_view component_name, bool is_static, bool allow_native_bridge, bool force_writable, bool shadows_entity_base, unordered_set<string>& member_names)
{
    FO_STACK_TRACE_ENTRY();

    for (size_t i = 1; i < registrar->GetPropertiesCount(); i++) {
        auto prop = registrar->GetPropertyByIndexUnsafe(i);

        if (prop->IsDisabled() || prop->IsComponentItself()) {
            continue;
        }
        if (prop->GetComponentName() != component_name) {
            continue;
        }

        string prop_type = MakeCsPropertyTypeName(prop);

        if (prop->IsNullable()) {
            prop_type += "?";
        }

        string prop_name = EscapeCsIdentifier(prop->GetNameWithoutComponent());

        if (allow_native_bridge && CanUseManagedPropertyBridge(prop)) {
            AppendNativeProperty(out, prop, is_static, shadows_entity_base, member_names);
        }
        else {
            AppendProperty(out, prop_type, prop_name, force_writable || prop->IsMutable(), is_static, shadows_entity_base, member_names);
        }
    }
}

static auto MakeSortedComponents(const EntityTypeDesc& desc) -> vector<pair<string, ptr<const Property>>>
{
    FO_STACK_TRACE_ENTRY();

    FO_VERIFY_AND_THROW(desc.PropRegistrar.as_nptr(), "Entity type has no property registrar");

    vector<pair<string, ptr<const Property>>> result;
    result.reserve(desc.PropRegistrar->GetComponents().size());

    for (const auto& [component_name, prop] : desc.PropRegistrar->GetComponents()) {
        result.emplace_back(component_name, prop);
    }

    // GetComponents() is an unordered_map, and the generated file is committed: without a fixed order the
    // same input regenerates as a diff of every component class
    std::ranges::sort(result, {}, [](const auto& entry) -> const string& { return entry.first; });
    return result;
}

static void AppendComponentAccessors(ostringstream& out, string_view owner_type_name, const EntityTypeDesc& desc, bool is_static, unordered_set<string>& member_names)
{
    FO_STACK_TRACE_ENTRY();

    for (const auto& [component_name, prop] : MakeSortedComponents(desc)) {
        string component_type = strex("{}{}Component", owner_type_name, component_name).str();
        string accessor_name = EscapeCsIdentifier(component_name);
        string has_accessor_name = EscapeCsIdentifier(strex("Has{}", component_name).str());

        if (member_names.emplace(accessor_name).second) {
            out << CS_INDENT << "public ";

            if (is_static) {
                out << "static ";
            }

            out << component_type << " " << accessor_name << "\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    get\n";
            out << CS_INDENT << "    {\n";
            out << CS_INDENT << "        if (!" << has_accessor_name << ") {\n";
            out << CS_INDENT << "            throw new InvalidOperationException(\"Component is not present on entity\");\n";
            out << CS_INDENT << "        }\n\n";
            out << CS_INDENT << "        return global::FOnline.Native.WrapEntityNotNull<" << component_type << ">(" << MakeTargetPtrExpression(is_static, false) << ");\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "}\n\n";
        }

        if (member_names.emplace(has_accessor_name).second) {
            out << CS_INDENT << "public ";

            if (is_static) {
                out << "static ";
            }

            out << "bool " << has_accessor_name << "\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    get\n";
            out << CS_INDENT << "    {\n";
            out << CS_INDENT << "        return global::FOnline.Native.GetPropertyValue<bool>(" << MakeTargetPtrExpression(is_static, false) << ", " << prop->GetRegIndex() << ");\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "}\n\n";
        }

        ignore_unused(prop);
    }
}

static void AppendEventAccessors(ostringstream& out, string_view owner_type_name, const EntityTypeDesc& desc, bool is_static, unordered_set<string>& member_names)
{
    FO_STACK_TRACE_ENTRY();

    for (const EntityEventDesc& event : desc.Events) {
        string event_type = strex("{}{}Event", owner_type_name, event.Name).str();
        string event_name = EscapeCsIdentifier(event.Name);

        if (!member_names.emplace(event_name).second) {
            continue;
        }

        out << CS_INDENT << "public ";

        if (is_static) {
            out << "static ";
        }

        out << event_type << " " << event_name << "\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    get\n";
        out << CS_INDENT << "    {\n";
        out << CS_INDENT << "        return new " << event_type << "(" << MakeTargetPtrExpression(is_static, false) << ");\n";
        out << CS_INDENT << "    }\n";
        out << CS_INDENT << "}\n\n";
    }
}

static void AppendEntityClass(ostringstream& out, string_view class_name, string_view base_name, const EntityTypeDesc& desc, string_view target_name, const ManagedAbiManifest& abi, string_view native_owner_name, bool is_fixed_type, bool data_only)
{
    FO_STACK_TRACE_ENTRY();

    bool is_static = desc.IsGlobal && class_name == "Game";
    unordered_set<string> member_names;

    // The C# class name (`class_name`) can differ from the native entity-type owner used for property/method/event
    // bridging and component-class naming (`owner`)
    string_view owner = native_owner_name.empty() ? class_name : native_owner_name;

    if (is_static) {
        out << "public static partial class Game\n";
    }
    else {
        out << "public partial class " << EscapeCsIdentifier(class_name) << " : " << EscapeCsIdentifier(base_name) << "\n";
    }

    out << "{\n";

    if (!is_static) {
        out << CS_INDENT << "public " << EscapeCsIdentifier(class_name) << "() : base()\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "}\n\n";
        out << CS_INDENT << "internal " << EscapeCsIdentifier(class_name) << "(IntPtr entityPtr) : base(entityPtr)\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "}\n\n";
    }

    AppendComponentAccessors(out, owner, desc, is_static, member_names);
    // Mirror AngelScript's get_Proto() as a Proto property resolving through the same Game proto getter the
    // generated code already emits
    if (!is_static && !is_fixed_type && !data_only && desc.HasProtos && member_names.emplace("Proto").second) {
        out << CS_INDENT << "public Proto" << owner << " Proto\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    get\n";
        out << CS_INDENT << "    {\n";
        out << CS_INDENT << "        return Game.GetProto" << owner << "(ProtoId);\n";
        out << CS_INDENT << "    }\n";
        out << CS_INDENT << "}\n\n";
    }
    // A non-static entity class derives from the Entity base (`: base_name`), so a Name/Id/ProtoId/IsDestroyed
    // property shadows the base member and needs `new`; the static `Game` class has no such base
    AppendEntityProperties(out, desc.PropRegistrar.get(), {}, is_static, true, false, !is_static, member_names);

    // A prototype is authored data, not a live entity: it carries the type's properties and components and stops
    // there
    if (data_only) {
        out << CS_INDENT << "public override bool IsAlwaysCovered\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    get\n";
        out << CS_INDENT << "    {\n";
        out << CS_INDENT << "        return true;\n";
        out << CS_INDENT << "    }\n";
        out << CS_INDENT << "}\n";
        out << "}\n\n";
        return;
    }

    AppendEventAccessors(out, owner, desc, is_static, member_names);
    // Entity synchronization exists only on the server; client and mapper scripts run single-threaded, so a
    // cover contract there would name a guarantee with no mechanism behind it
    bool is_synced_entity_owner = !is_static && !is_fixed_type && target_name == "Server";

    AppendMethods(out, desc.Methods, owner, is_static, false, true, is_synced_entity_owner, member_names, abi);
    AppendEntityHolderAccessors(out, owner, desc, target_name, is_static, member_names, abi);

    if (is_static) {
        if (!HasMethodSignature(desc.Methods, "Log", "void", {"string"})) {
            out << CS_INDENT << "public static void Log(string text)\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    global::FOnline.Native.Log(text);\n";
            out << CS_INDENT << "}\n\n";
        }
        if (!HasMethodSignature(desc.Methods, "GetHashStr", "string", {"ulong"})) {
            out << CS_INDENT << "public static string GetHashStr(ulong value)\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    return global::FOnline.Native.GetHashStrFromHash(value);\n";
            out << CS_INDENT << "}\n\n";
        }
        if (target_name == "Server" && member_names.emplace("Destroy").second) {
            out << CS_INDENT << "public static void Destroy<T>(T? entity) where T : Entity\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    if (entity != null) {\n";
            out << CS_INDENT << "        DestroyEntity(entity);\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "}\n\n";

            out << CS_INDENT << "public static void Destroy<T>(System.Collections.Generic.List<T>? entities) where T : Entity\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    if (entities == null) {\n";
            out << CS_INDENT << "        return;\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "    for (int __i = 0; __i < entities.Count; __i++) {\n";
            out << CS_INDENT << "        DestroyEntity(entities[__i]);\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "}\n\n";
        }
    }

    out << "}\n\n";
}

static void AppendComponentClasses(ostringstream& out, string_view owner_type_name, const EntityTypeDesc& desc)
{
    FO_STACK_TRACE_ENTRY();

    for (const auto& [component_name, prop] : MakeSortedComponents(desc)) {
        unordered_set<string> member_names;
        string component_type = strex("{}{}Component", owner_type_name, component_name).str();

        out << "public partial class " << EscapeCsIdentifier(component_type) << " : Entity\n";
        out << "{\n";
        out << CS_INDENT << "public " << EscapeCsIdentifier(component_type) << "() : base()\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "}\n\n";
        out << CS_INDENT << "internal " << EscapeCsIdentifier(component_type) << "(IntPtr entityPtr) : base(entityPtr)\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "}\n\n";
        // A component class derives from Entity (`: Entity`), so its shadow-named properties need `new`
        AppendEntityProperties(out, desc.PropRegistrar.get(), component_name, false, true, false, true, member_names);
        out << "}\n\n";

        ignore_unused(prop);
    }
}

static void AppendEntityHolderAccessors(ostringstream& out, string_view owner_type_name, const EntityTypeDesc& desc, string_view target_name, bool is_static, unordered_set<string>& member_names, const ManagedAbiManifest& abi)
{
    FO_STACK_TRACE_ENTRY();

    if (desc.HolderEntries.empty()) {
        return;
    }

    vector<pair<string, const EntityTypeDesc::HolderEntryDesc*>> holder_entries;
    holder_entries.reserve(desc.HolderEntries.size());

    for (const auto& [entry_name, holder_entry] : desc.HolderEntries) {
        holder_entries.emplace_back(entry_name.as_str(), &holder_entry);
    }

    std::ranges::sort(holder_entries, {}, [](const auto& entry) -> const string& { return entry.first; });

    bool can_create_inner_entities = target_name == "Server";
    string entity_ptr = string {MakeTargetPtrExpression(is_static, false)};

    for (const auto& [entry_name, holder_entry] : holder_entries) {
        string target_type {holder_entry->TargetType.as_str()};
        string escaped_target_type = EscapeCsIdentifier(target_type);
        string escaped_entry_name = EscapeCsIdentifier(entry_name);
        string entry_literal = EscapeCsStringLiteral(entry_name);
        string add_method_name = strex("Add{}", escaped_entry_name).str();
        string has_method_name = strex("Has{}s", escaped_entry_name).str();
        string get_all_method_name = strex("Get{}s", escaped_entry_name).str();
        string get_one_method_name = strex("Get{}", escaped_entry_name).str();
        nptr<const ManagedAbiInnerEntry> abi_entry = FindManagedAbiInnerEntry(abi, owner_type_name, entry_name);
        FO_VERIFY_AND_THROW(abi_entry, "Managed inner entry is missing from the ABI manifest", owner_type_name, entry_name);
        int32_t entry_id = abi_entry->Id;
        ignore_unused(entry_literal);

        if (can_create_inner_entities && member_names.emplace(add_method_name).second) {
            out << CS_INDENT << "public ";

            if (is_static) {
                out << "static ";
            }

            out << escaped_target_type << " " << add_method_name << "(";

            if (desc.HasProtos) {
                out << "hstring pid";
            }

            out << ")\n";
            out << CS_INDENT << "{\n";

            if (desc.HasProtos) {
                out << CS_INDENT << "    IntPtr __ptr = global::FOnline.Native.CreateInnerEntity(" << entity_ptr << ", " << entry_id << ", pid.Value);\n";
            }
            else {
                out << CS_INDENT << "    IntPtr __ptr = global::FOnline.Native.CreateInnerEntity(" << entity_ptr << ", " << entry_id << ", IntPtr.Zero);\n";
            }

            out << CS_INDENT << "    global::FOnline.Invariant.Verify(__ptr != IntPtr.Zero, \"Inner entity creation failed\");\n";
            out << CS_INDENT << "    return global::FOnline.Native.WrapEntityNotNull<" << escaped_target_type << ">(__ptr);\n";
            out << CS_INDENT << "}\n\n";
        }

        if (member_names.emplace(has_method_name).second) {
            out << CS_INDENT << "public ";

            if (is_static) {
                out << "static ";
            }

            out << "bool " << has_method_name << "()\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    return global::FOnline.Native.HasInnerEntities(" << entity_ptr << ", " << entry_id << ");\n";
            out << CS_INDENT << "}\n\n";
        }

        if (member_names.emplace(get_all_method_name).second) {
            out << CS_INDENT << "public ";

            if (is_static) {
                out << "static ";
            }

            out << "int " << get_all_method_name << "(" << escaped_target_type << "[] buffer)\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    global::FOnline.InnerEntityFillFrame __scratch = default;\n";
            out << CS_INDENT << "    int __required = global::FOnline.Native.FillInnerEntities(" << entity_ptr << ", " << entry_id << ", ref __scratch[0], 256);\n";
            out << CS_INDENT << "    if (__required > 256) {\n";
            out << CS_INDENT << "        global::System.IntPtr[] __heap = new global::System.IntPtr[__required];\n";
            out << CS_INDENT << "        __required = global::FOnline.Native.FillInnerEntities(" << entity_ptr << ", " << entry_id << ", ref __heap[0], __required);\n";
            out << CS_INDENT << "        int __n = global::System.Math.Min(__required, buffer.Length);\n";
            out << CS_INDENT << "        for (int __i = 0; __i < __n; __i++) {\n";
            out << CS_INDENT << "            buffer[__i] = global::FOnline.Native.WrapEntityNotNull<" << escaped_target_type << ">(__heap[__i]);\n";
            out << CS_INDENT << "        }\n";
            out << CS_INDENT << "        return __required;\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "    int __copy = global::System.Math.Min(__required, buffer.Length);\n";
            out << CS_INDENT << "    for (int __i = 0; __i < __copy; __i++) {\n";
            out << CS_INDENT << "        buffer[__i] = global::FOnline.Native.WrapEntityNotNull<" << escaped_target_type << ">(__scratch[__i]);\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "    return __required;\n";
            out << CS_INDENT << "}\n\n";

            out << CS_INDENT << "public ";

            if (is_static) {
                out << "static ";
            }

            out << "System.Collections.Generic.List<" << escaped_target_type << "> " << get_all_method_name << "()\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    global::FOnline.InnerEntityFillFrame __scratch = default;\n";
            out << CS_INDENT << "    int __count = global::FOnline.Native.FillInnerEntities(" << entity_ptr << ", " << entry_id << ", ref __scratch[0], 256);\n";
            out << CS_INDENT << "    if (__count > 256) {\n";
            out << CS_INDENT << "        global::System.IntPtr[] __heap = new global::System.IntPtr[__count];\n";
            out << CS_INDENT << "        __count = global::FOnline.Native.FillInnerEntities(" << entity_ptr << ", " << entry_id << ", ref __heap[0], __count);\n";
            out << CS_INDENT << "        System.Collections.Generic.List<" << escaped_target_type << "> __grown = new System.Collections.Generic.List<" << escaped_target_type << ">(__count);\n";
            out << CS_INDENT << "        for (int __i = 0; __i < __count; __i++) {\n";
            out << CS_INDENT << "            __grown.Add(global::FOnline.Native.WrapEntityNotNull<" << escaped_target_type << ">(__heap[__i]));\n";
            out << CS_INDENT << "        }\n";
            out << CS_INDENT << "        return __grown;\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "    System.Collections.Generic.List<" << escaped_target_type << "> __result = new System.Collections.Generic.List<" << escaped_target_type << ">(__count);\n";
            out << CS_INDENT << "    for (int __i = 0; __i < __count; __i++) {\n";
            out << CS_INDENT << "        __result.Add(global::FOnline.Native.WrapEntityNotNull<" << escaped_target_type << ">(__scratch[__i]));\n";
            out << CS_INDENT << "    }\n";
            out << CS_INDENT << "    return __result;\n";
            out << CS_INDENT << "}\n\n";
        }

        if (!is_static && member_names.emplace(get_one_method_name).second) {
            out << CS_INDENT << "public " << escaped_target_type << "? " << get_one_method_name << "(ident id)\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    IntPtr __ptr = global::FOnline.Native.GetInnerEntity(" << entity_ptr << ", " << entry_id << ", id.value);\n";
            out << CS_INDENT << "    return __ptr != IntPtr.Zero ? global::FOnline.Native.WrapEntity<" << escaped_target_type << ">(__ptr) : null;\n";
            out << CS_INDENT << "}\n\n";
        }
    }
}

