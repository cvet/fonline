auto ManagedScriptBaker::CollectSourceFiles(const FileCollection& files, const vector<std::filesystem::path>& dir_source_files, const vector<string>& extra_sources, string_view assembly_name, string_view target_name, const std::filesystem::path& config_dir) -> vector<std::filesystem::path>
{
    FO_STACK_TRACE_ENTRY();

    vector<std::filesystem::path> result;
    unordered_set<string> unique_paths;

    auto add_source = [&](const std::filesystem::path& path) {
        std::error_code ec;
        auto normalized_path = std::filesystem::weakly_canonical(path, ec);
        string key = strex("{}", (ec ? path.lexically_normal() : normalized_path).string()).str();

        if (unique_paths.emplace(key).second) {
            result.emplace_back(ec ? path.lexically_normal() : normalized_path);
        }
    };

    for (const std::filesystem::path& source_file : dir_source_files) {
        add_source(source_file);
    }

    for (const FileHeader& file : files) {
        if (strex(file.GetPath()).get_file_extension() != "cs") {
            continue;
        }
        if (!file.GetDataSource()->IsDiskDir()) {
            continue;
        }

        std::filesystem::path disk_path = fs::make_path(file.GetDiskPath());

        if (IsGeneratedManagedArtifactFileName(strex("{}", disk_path.filename().string()).str())) {
            continue;
        }
        if (IsGeneratedManagedApiFile(disk_path)) {
            continue;
        }

        add_source(disk_path);
    }

    for (const string& source_path : CollectScopedValues(extra_sources, assembly_name, target_name)) {
        std::filesystem::path source_file_path = ResolveManagedPath(config_dir, source_path);

        if (IsGeneratedManagedArtifactFileName(strex("{}", source_file_path.filename().string()).str())) {
            continue;
        }
        if (IsGeneratedManagedApiFile(source_file_path)) {
            continue;
        }

        add_source(source_file_path);
    }

    std::ranges::sort(result, {}, [](const std::filesystem::path& path) { return path.string(); });
    return result;
}

auto ManagedScriptBaker::CollectReferences(const vector<string>& extra_references, string_view assembly_name, string_view target_name, const std::filesystem::path& config_dir) -> vector<string>
{
    FO_STACK_TRACE_ENTRY();

    vector<string> result;
    unordered_set<string> unique_refs(result.begin(), result.end());

    for (const string& reference_value : CollectScopedValues(extra_references, assembly_name, target_name)) {
        bool is_path_reference = reference_value.find('\\') != string::npos || reference_value.find('/') != string::npos || std::filesystem::path(fs::make_path(reference_value)).extension() == ".dll";
        string reference = reference_value;

        if (is_path_reference) {
            reference = ResolveManagedPath(config_dir, reference_value).string();
        }

        if (unique_refs.emplace(reference).second) {
            result.emplace_back(reference);
        }
    }

    std::ranges::sort(result);
    return result;
}

auto ManagedScriptBaker::GetManagedGeneratedDir(string_view dir_override, const std::filesystem::path& config_dir) -> std::filesystem::path
{
    FO_STACK_TRACE_ENTRY();

    // Empty targets the build GeneratedSource tree (the same one native codegen writes to), so generated
    // managed scripts stay out of the authored source tree unless the project explicitly roots them there
    std::filesystem::path generated_dir = dir_override.empty() ? std::filesystem::path {FO_GENERATED_SOURCE_DIR} / "Managed" : ResolveManagedPath(config_dir, dir_override);

    std::error_code ec;
    std::filesystem::create_directories(generated_dir, ec);

    if (ec) {
        throw ManagedScriptBakerException("Can't create Managed generated directory", generated_dir.string());
    }

    auto canonical_dir = std::filesystem::weakly_canonical(generated_dir, ec);
    return ec ? generated_dir.lexically_normal() : canonical_dir;
}

auto ManagedScriptBaker::RunCommand(string_view command, string_view fail_message) -> void
{
    FO_STACK_TRACE_ENTRY();

    string pending_output;

    auto log_complete_lines = [&pending_output](string_view chunk) {
        pending_output.append(chunk);
        size_t line_end = pending_output.find('\n');

        while (line_end != string::npos) {
            string line = TrimString(pending_output.substr(0, line_end));

            if (!line.empty()) {
                logging::write("{}", line);
            }

            pending_output.erase(0, line_end + 1);
            line_end = pending_output.find('\n');
        }
    };

    // std::system would hand the command to a console of its own, which a windowed host such as a server baking
    // on startup shows as a separate terminal; the hidden-window runner routes the compiler output to the log instead
#if FO_WINDOWS
    int32_t exit_code = winapi::run_process_capturing_output(strex("cmd.exe /d /s /c \"{}\"", command).str(), log_complete_lines);
#else
    int32_t exit_code = posix::run_process_capturing_output(string(command), log_complete_lines);
#endif

    log_complete_lines("\n");

    if (exit_code != 0) {
        throw ManagedScriptBakerException(fail_message, exit_code);
    }
}

static auto GetManagedBakeStamp(const BakingContext& context, string_view target_name, const vector<std::filesystem::path>& source_files, const vector<string>& references, const std::filesystem::path& managed_host_source, const ManagedProjectAnalysis& analysis, const std::filesystem::path& generated_dir, string_view project_name) -> uint64_t
{
    FO_STACK_TRACE_ENTRY();

    uint64_t stamp = 1;

    auto merge_disk_file = [&](const string& path) {
        if (uint64_t write_time = fs::last_write_time(path); write_time != 0) {
            stamp = std::max(stamp, write_time);
        }
    };

    for (const std::filesystem::path& source_file : source_files) {
        string source_file_path = strex("{}", source_file.string()).str();
        merge_disk_file(source_file_path);
    }

    merge_disk_file(strex("{}", managed_host_source.string()).str());

    for (string_view suffix : GENERATED_MANAGED_API_SUFFIXES) {
        merge_disk_file(strex("{}", (generated_dir / fs::make_path(MakeGeneratedManagedApiFileName(target_name, suffix))).string()).str());
    }

    merge_disk_file(strex("{}", (generated_dir / fs::make_path(MakeGeneratedManagedUnifiedProjectFileName(project_name))).string()).str());
    merge_disk_file(strex("{}", (generated_dir / fs::make_path(MakeGeneratedManagedUnifiedProjectFileName(MANAGED_HOST_PROJECT_NAME))).string()).str());
    merge_disk_file(strex("{}", (generated_dir / fs::make_path(MakeGeneratedManagedSolutionFileName(project_name))).string()).str());

    if (optional<std::filesystem::path> runtime_dir = FindManagedRuntimeDirectory(); runtime_dir.has_value()) {
        merge_disk_file(strex("{}", (*runtime_dir / fs::make_path(MANAGED_RUNTIME_MANIFEST_FILE)).string()).str());
    }

    for (const string& reference : references) {
        if (reference.find('/') != string::npos || reference.find('\\') != string::npos || reference.find(':') != string::npos || strex(reference).get_file_extension() == "dll") {
            merge_disk_file(reference);
        }
    }

    // An analyzer decides which diagnostics are reported, so editing one must recompile the scripts:
    // otherwise an added rule stays silent until something else changes, reading as a rule that found nothing
    for (const string& analyzer_project : analysis.AnalyzerProjects) {
        merge_disk_file(analyzer_project);
    }

    for (const string& additional_file : analysis.AdditionalFiles) {
        merge_disk_file(additional_file);
    }

    // The same covers .editorconfig, where severities live: the stamp walks up from each source file exactly
    // as Roslyn resolves it, because a severity is as much a compilation input as the analyzer reading it
    unordered_set<string> visited_dirs;

    for (const std::filesystem::path& source_file : source_files) {
        std::filesystem::path dir = source_file.parent_path();

        while (!dir.empty()) {
            string dir_key = strex("{}", dir.string()).str();

            if (!visited_dirs.emplace(dir_key).second) {
                break;
            }

            merge_disk_file(strex("{}", (dir / ".editorconfig").string()).str());

            std::filesystem::path parent = dir.parent_path();

            if (parent == dir) {
                break;
            }

            dir = parent;
        }
    }

    if (context.BakedFiles) {
        string target_lower = strex(target_name).lower();
        FileHeader metadata_header = context.BakedFiles->ReadFileHeader(strex("Metadata.fometa-{}", target_lower));

        if (metadata_header) {
            stamp = std::max(stamp, metadata_header.GetWriteTime());
        }
    }

    return stamp;
}

static auto FindManagedHostSource(const vector<string>& source_dirs, const std::filesystem::path& config_dir) -> std::filesystem::path
{
    FO_STACK_TRACE_ENTRY();

    for (const string& source_dir_value : source_dirs) {
        std::filesystem::path source_dir = ResolveManagedPath(config_dir, source_dir_value);
        array candidates {
            source_dir / "ManagedHost" / MANAGED_HOST_SOURCE_FILE_NAME,
            source_dir.parent_path() / "ManagedHost" / MANAGED_HOST_SOURCE_FILE_NAME,
        };

        for (const std::filesystem::path& candidate : candidates) {
            std::error_code ec;

            if (!std::filesystem::is_regular_file(candidate, ec) || ec) {
                continue;
            }

            auto canonical_path = std::filesystem::weakly_canonical(candidate, ec);
            return ec ? candidate.lexically_normal() : canonical_path;
        }
    }

    throw ManagedScriptBakerException("Managed load-context host source not found", MANAGED_HOST_SOURCE_FILE_NAME);
}

