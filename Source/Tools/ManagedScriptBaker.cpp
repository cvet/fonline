// Emits Game.SetPropertyGetter / Game.AddPropertySetter overloads, one group per non-global entity type, so scripts
// can register managed virtual-property callbacks the same way AngelScript does
static void AppendRemoteCallerSurface(ostringstream& out, const EngineMetadata& meta, string_view target_name)
{
    FO_STACK_TRACE_ENTRY();

    vector<ptr<const RemoteCallDesc>> cs_calls;

    for (const auto& call : (*meta.GetOutboundRemoteCalls()) | std::views::values) {
        cs_calls.emplace_back(&call);
    }

    if (cs_calls.empty()) {
        return;
    }

    std::ranges::sort(cs_calls, {}, [](ptr<const RemoteCallDesc> call) { return call->Name.as_str(); });

    out << "public readonly struct RemoteCaller\n";
    out << "{\n";
    out << CS_INDENT << "private readonly Entity _caller;\n";
    out << "\n";
    out << CS_INDENT << "public RemoteCaller(Entity caller)\n";
    out << CS_INDENT << "{\n";
    out << CS_INDENT << "    _caller = caller;\n";
    out << CS_INDENT << "}\n";

    for (ptr<const RemoteCallDesc> call : cs_calls) {
        string name = string(call->Name.as_str());
        auto arg_decls = MakeCsArgumentDeclarations(call->Args);
        auto arg_names = MakeCsArgumentNames(call->Args);
        string args_array = arg_names.empty() ? "new object?[0]" : strex("new object?[] {{ {} }}", JoinCsCommaList(arg_names)).str();

        out << "\n";
        out << CS_INDENT << "public void " << EscapeCsIdentifier(name) << "(" << JoinCsCommaList(arg_decls) << ")\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    global::FOnline.Native.SendRemoteCall(_caller, \"" << name << "\", " << args_array << ");\n";
        out << CS_INDENT << "}\n";
    }

    out << "}\n\n";

    if (target_name == "Server") {
        out << "public partial class Player\n";
        out << "{\n";
        out << CS_INDENT << "public RemoteCaller ClientCall => new RemoteCaller(this);\n";
        out << "}\n\n";
        out << "public partial class Critter\n";
        out << "{\n";
        out << CS_INDENT << "public RemoteCaller PlayerClientCall => new RemoteCaller(this);\n";
        out << "}\n\n";
    }
    else {
        out << "public partial class Player\n";
        out << "{\n";
        out << CS_INDENT << "public RemoteCaller ServerCall => new RemoteCaller(this);\n";
        out << "}\n\n";
    }
}

// One adapter per callback signature the ABI frame can carry: it reads handles and fixed values from the frame and
// invokes the delegate directly; a delegate shape it does not recognize takes the boxed Native.InvokeCallback path
static void AppendCallbackAdapters(ostringstream& out, const EngineMetadata& meta, string_view target_name, const vector<pair<string, ComplexTypeDesc>>& callbacks)
{
    FO_STACK_TRACE_ENTRY();

    out << "internal static class CallbackAdapters\n";
    out << "{\n";

    set<string> emitted_keys;

    for (const auto& [name, type] : callbacks) {
        FO_VERIFY_AND_THROW(type.CallbackArgs, "Callback type has no argument list");
        AppendCallbackAdapter(out, emitted_keys, name, type.CallbackArgs->front(), span(*type.CallbackArgs).subspan(1));
    }

    // An inbound remote call has no delegate type of its own: its handler is an Action over the calling Player
    // (server side only) and the wire arguments, so the signature is keyed exactly as the backend keys its plan
    vector<ptr<const RemoteCallDesc>> inbound_calls;

    for (const auto& call : (*meta.GetInboundRemoteCalls()) | std::views::values) {
        inbound_calls.emplace_back(&call);
    }

    std::ranges::sort(inbound_calls, {}, [](ptr<const RemoteCallDesc> call) { return call->Name.as_str(); });

    for (ptr<const RemoteCallDesc> call : inbound_calls) {
        vector<ComplexTypeDesc> args;
        args.reserve(call->Args.size() + 1);

        if (target_name == "Server") {
            args.emplace_back(meta.ResolveComplexType("Player"));
        }

        for (const auto& arg : call->Args) {
            args.emplace_back(arg.Type);
        }

        AppendCallbackAdapter(out, emitted_keys, {}, ComplexTypeDesc {}, args);
    }

    out << "}\n\n";
}

// Emits one adapter unless the frame cannot carry the signature or its key is already covered; an empty delegate name
// means the signature has no generated delegate type, so only the System.Action / System.Func shapes are matched
static void AppendCallbackAdapter(ostringstream& out, set<string>& emitted_keys, string_view delegate_name, const ComplexTypeDesc& ret, const_span<ComplexTypeDesc> args)
{
    FO_STACK_TRACE_ENTRY();

    ManagedAbiCallbackLayout layout = BuildManagedAbiCallbackLayout(ret, args);

    // System.Action and System.Func stop at sixteen arguments
    bool system_shapes = args.size() <= 16;

    if (!layout.Supported || (delegate_name.empty() && !system_shapes)) {
        return;
    }

    string key = MakeManagedAbiCallbackKey(ret, args);

    if (!emitted_keys.emplace(key).second) {
        return;
    }

    if (emitted_keys.size() > 1) {
        out << "\n";
    }

    string name {delegate_name};
    string ret_type = MakeCsTypeName(ret);
    vector<string> arg_types;
    vector<string> arg_names;

    out << CS_INDENT << "internal static void Adapt_" << key << "(global::System.Delegate handler, ref byte frame, int frameSize)\n";
    out << CS_INDENT << "{\n";
    out << CS_INDENT << "    global::FOnline.Invariant.Verify(frameSize == " << layout.FrameSize << ", \"Callback frame size must match the generated layout\");\n";

    for (size_t i = 0; i < args.size(); i++) {
        string arg_type = MakeCsTypeName(args[i]);
        string arg_name = strex("__a{}", i).str();
        const ManagedAbiSlot& slot = layout.Args[i];
        string slot_ref = strex("ref global::System.Runtime.CompilerServices.Unsafe.Add(ref frame, {})", slot.Offset).str();

        if (slot.Kind == ManagedAbiValueKind::Handle) {
            string_view wrap = args[i].BaseType.IsRefType ? "WrapRefNotNull" : "WrapEntityNotNull";
            out << CS_INDENT << "    " << arg_type << " " << arg_name << " = global::FOnline.Native." << wrap << "<" << arg_type << ">((global::System.IntPtr)global::System.Runtime.CompilerServices.Unsafe.ReadUnaligned<long>(" << slot_ref << "));\n";
        }
        else {
            out << CS_INDENT << "    " << arg_type << " " << arg_name << " = global::System.Runtime.CompilerServices.Unsafe.ReadUnaligned<" << arg_type << ">(" << slot_ref << ");\n";
        }

        arg_types.emplace_back(arg_type);
        arg_names.emplace_back(arg_name);
    }

    string invoke_list = JoinCsCommaList(arg_names);
    string system_args = JoinCsCommaList(arg_types);
    string system_args_prefix = args.empty() ? string {} : system_args + ", ";

    auto write_result = [&](string_view variable) -> string {
        if (!ret) {
            return {};
        }

        return strex("global::System.Runtime.CompilerServices.Unsafe.WriteUnaligned({}, {});", strex("ref global::System.Runtime.CompilerServices.Unsafe.Add(ref frame, {})", layout.ResultOffset).str(), variable).str();
    };

    auto append_branch = [&](string_view delegate_type, string_view variable, string_view call_statement) {
        out << CS_INDENT << "    if (handler is " << delegate_type << " " << variable << ") {\n";
        out << CS_INDENT << "        using global::FOnline.ScriptSynchronizationContext context = global::FOnline.ScriptSynchronizationContext.Enter(false);\n";
        out << CS_INDENT << "        try {\n";
        out << CS_INDENT << "            " << call_statement << "\n";

        if (ret) {
            out << CS_INDENT << "            " << write_result("__r") << "\n";
        }

        out << CS_INDENT << "        }\n";
        out << CS_INDENT << "        catch (Exception ex) {\n";
        out << CS_INDENT << "            global::FOnline.ScriptExceptions.Record(ex, false);\n";
        out << CS_INDENT << "            throw;\n";
        out << CS_INDENT << "        }\n";
        out << CS_INDENT << "        return;\n";
        out << CS_INDENT << "    }\n";
    };

    if (ret) {
        if (!name.empty()) {
            append_branch(EscapeCsIdentifier(name), "typed", strex("{} __r = typed({});", ret_type, invoke_list).str());
        }
        if (system_shapes) {
            append_branch(strex("global::System.Func<{}{}>", system_args_prefix, ret_type).str(), "func", strex("{} __r = func({});", ret_type, invoke_list).str());
        }
    }
    else {
        if (!name.empty()) {
            append_branch(EscapeCsIdentifier(name), "typed", strex("typed({});", invoke_list).str());
            append_branch(EscapeCsIdentifier(name + "Async"), "typedAsync", strex("global::FOnline.Native.CompleteCallbackTask(typedAsync({}));", invoke_list).str());
        }
        if (system_shapes) {
            append_branch(args.empty() ? string("global::System.Action") : strex("global::System.Action<{}>", system_args).str(), "action", strex("action({});", invoke_list).str());
            append_branch(strex("global::System.Func<{}global::System.Threading.Tasks.Task>", system_args_prefix).str(), "asyncFunc", strex("global::FOnline.Native.CompleteCallbackTask(asyncFunc({}));", invoke_list).str());
        }
    }

    if (args.empty()) {
        out << CS_INDENT << "    object?[] __args = global::System.Array.Empty<object?>();\n";
    }
    else {
        out << CS_INDENT << "    object?[] __args = new object?[] { " << invoke_list << " };\n";
    }

    if (ret) {
        out << CS_INDENT << "    " << ret_type << " __boxedResult = global::FOnline.Native.UnboxArg<" << ret_type << ">(global::FOnline.Native.InvokeCallback(handler, __args));\n";
        out << CS_INDENT << "    " << write_result("__boxedResult") << "\n";
    }
    else {
        out << CS_INDENT << "    global::FOnline.Native.InvokeCallback(handler, __args);\n";
    }

    out << CS_INDENT << "}\n";
}

// as one non-generic overload per distinct simple property value type; overload resolution then picks
// the match from the supplied setter method group with no explicit type argument
static void AppendPropertyCallbackRegistrars(ostringstream& out, const EngineMetadata& meta)
{
    FO_STACK_TRACE_ENTRY();

    unordered_set<string> enum_names;

    for (const auto& enum_entry : MakeSortedEnums(meta)) {
        enum_names.emplace(enum_entry.first);
    }

    vector<pair<string, string>> property_adapter_types;

    out << "public static partial class Game\n";
    out << "{\n";

    for (const auto& [type_name, desc] : MakeSortedEntityTypes(meta.GetEntityTypes())) {
        if (desc->IsGlobal) {
            continue;
        }

        string property_enum_name = strex("{}Property", type_name).str();

        if (!enum_names.contains(property_enum_name)) {
            continue;
        }

        auto registrar = meta.GetPropertyRegistrar(type_name);

        if (!registrar) {
            continue;
        }

        string entity_type = EscapeCsIdentifier(type_name);
        string enum_type = EscapeCsIdentifier(property_enum_name);

        out << CS_INDENT << "public static void SetPropertyGetter<T>(" << enum_type << " property, global::System.Func<" << entity_type << ", T> getter)\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    global::FOnline.Native.SetPropertyGetter(\"" << type_name << "\", property.ToString(), getter);\n";
        out << CS_INDENT << "}\n\n";

        // Deferred (post-set) reaction setter: receives only the entity, so a single non-generic
        // Action<Entity> overload covers every property of this type
        out << CS_INDENT << "public static void AddPropertyDeferredSetter(" << enum_type << " property, global::System.Action<" << entity_type << "> setter)\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    global::FOnline.Native.AddPropertyDeferredSetter(\"" << type_name << "\", property.ToString(), setter);\n";
        out << CS_INDENT << "}\n\n";

        // AngelScript's AddPropertySetter accepts both the value-transforming form and an entity-only post-set
        // reaction, so the managed side splits them by arity
        out << CS_INDENT << "public static void AddPropertySetter(" << enum_type << " property, global::System.Action<" << entity_type << "> setter)\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    global::FOnline.Native.AddPropertyDeferredSetter(\"" << type_name << "\", property.ToString(), setter);\n";
        out << CS_INDENT << "}\n\n";

        for (string_view method_name : {"AddPropertyDeferredSetter", "AddPropertySetter"}) {
            out << CS_INDENT << "public static void " << method_name << "(" << enum_type << " property, global::System.Func<" << entity_type << ", global::System.Threading.Tasks.Task> setter)\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    global::FOnline.Native.AddPropertyDeferredSetter(\"" << type_name << "\", property.ToString(), setter);\n";
            out << CS_INDENT << "}\n\n";
        }

        unordered_set<string> seen_value_types;
        vector<string> value_types;

        for (size_t i = 1; i < registrar->GetPropertiesCount(); i++) {
            auto prop = registrar->GetPropertyByIndexUnsafe(i);

            if (prop->IsDict() || prop->IsArray()) {
                continue;
            }

            const BaseTypeDesc& base_type = prop->GetBaseType();

            if (base_type.IsRefType || base_type.IsEntity) {
                continue;
            }

            string value_type = MakeCsTypeName(prop->GetBaseType());

            if (seen_value_types.emplace(value_type).second) {
                property_adapter_types.emplace_back(entity_type, value_type);
                value_types.emplace_back(std::move(value_type));
            }
        }

        std::ranges::sort(value_types);

        for (const string& value_type : value_types) {
            out << CS_INDENT << "public static void AddPropertySetter(" << enum_type << " property, global::FOnline.PropertySetter<" << entity_type << ", " << value_type << "> setter)\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    global::FOnline.Native.AddPropertySetter(\"" << type_name << "\", property.ToString(), setter);\n";
            out << CS_INDENT << "}\n\n";

            out << CS_INDENT << "public static void AddPropertySetter(" << enum_type << " property, global::FOnline.PropertySetterWithProperty<" << entity_type << ", " << enum_type << ", " << value_type << "> setter)\n";
            out << CS_INDENT << "{\n";
            out << CS_INDENT << "    global::FOnline.Native.AddPropertySetterWithProperty(\"" << type_name << "\", property.ToString(), setter);\n";
            out << CS_INDENT << "}\n\n";
        }
    }

    out << "}\n\n";

    out << "internal static class PropertyCallbackAdapters\n";
    out << "{\n";

    for (const auto& [entity_type, value_type] : property_adapter_types) {
        const BaseTypeDesc* value_base = nullptr;

        for (const auto& type : meta.GetBaseTypes() | std::views::values) {
            if (MakeCsTypeName(type) == value_type && IsManagedAbiFixedPropertyValue(type)) {
                value_base = &type;
                break;
            }
        }

        if (value_base == nullptr || value_base->Size > MANAGED_ABI_PROPERTY_ADAPTER_STORAGE) {
            continue;
        }

        string getter_name = strex("AdaptGetter_{}_{}", entity_type, value_type).str();
        string setter_name = strex("AdaptSetter_{}_{}", entity_type, value_type).str();

        out << CS_INDENT << "[global::FOnline.CallableByEngine]\n";
        out << CS_INDENT << "internal static void " << getter_name << "(global::System.Delegate handler, global::System.IntPtr entityPtr, ref " << value_type << " result)\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    using global::FOnline.ScriptSynchronizationContext context = global::FOnline.ScriptSynchronizationContext.Enter(false);\n";
        out << CS_INDENT << "    try\n";
        out << CS_INDENT << "    {\n";
        out << CS_INDENT << "        " << entity_type << " entity = global::FOnline.Native.WrapEntityNotNull<" << entity_type << ">(entityPtr);\n";
        out << CS_INDENT << "        result = ((global::System.Func<" << entity_type << ", " << value_type << ">)handler)(entity);\n";
        out << CS_INDENT << "    }\n";
        out << CS_INDENT << "    catch (Exception ex)\n";
        out << CS_INDENT << "    {\n";
        out << CS_INDENT << "        global::FOnline.ScriptExceptions.Record(ex, false);\n";
        out << CS_INDENT << "        throw;\n";
        out << CS_INDENT << "    }\n";
        out << CS_INDENT << "}\n\n";

        out << CS_INDENT << "[global::FOnline.CallableByEngine]\n";
        out << CS_INDENT << "internal static void " << setter_name << "(global::System.Delegate handler, global::System.IntPtr entityPtr, ref " << value_type << " value)\n";
        out << CS_INDENT << "{\n";
        out << CS_INDENT << "    using global::FOnline.ScriptSynchronizationContext context = global::FOnline.ScriptSynchronizationContext.Enter(false);\n";
        out << CS_INDENT << "    try\n";
        out << CS_INDENT << "    {\n";
        out << CS_INDENT << "        " << entity_type << " entity = global::FOnline.Native.WrapEntityNotNull<" << entity_type << ">(entityPtr);\n";
        out << CS_INDENT << "        ((global::FOnline.PropertySetter<" << entity_type << ", " << value_type << ">)handler)(entity, ref value);\n";
        out << CS_INDENT << "    }\n";
        out << CS_INDENT << "    catch (Exception ex)\n";
        out << CS_INDENT << "    {\n";
        out << CS_INDENT << "        global::FOnline.ScriptExceptions.Record(ex, false);\n";
        out << CS_INDENT << "        throw;\n";
        out << CS_INDENT << "    }\n";
        out << CS_INDENT << "}\n\n";
    }

    out << "}\n\n";
}

static void AppendPropertyInfoAccessor(ostringstream& out, string_view type_name, ptr<const PropertyRegistrar> registrar, const map<int32_t, string>& enum_values)
{
    FO_STACK_TRACE_ENTRY();

    string enum_type = EscapeCsIdentifier(strex("{}Property", type_name).str());

    out << CS_INDENT << "public static void GetPropertyInfo(" << enum_type << " property, out bool isDisabled, out bool isVirtual, out bool isDict, out bool isArray, out bool isStringLike, out string enumName, out bool isInt, out bool isFloat, out bool isBool, out int baseSize, out bool isSynced)\n";
    out << CS_INDENT << "{\n";
    out << CS_INDENT << "    if (global::FOnline.Native.EnumToInt32(property) == 0) {\n";
    out << CS_INDENT << "        throw new ArgumentOutOfRangeException(nameof(property), \"None is not valid property entry in this context\");\n";
    out << CS_INDENT << "    }\n\n";
    out << CS_INDENT << "    switch (property)\n";
    out << CS_INDENT << "    {\n";

    for (size_t i = 1; i < registrar->GetPropertiesCount(); i++) {
        auto prop = registrar->GetPropertyByIndexUnsafe(i);
        auto enum_value = enum_values.find(numeric_cast<int32_t>(prop->GetRegIndex()));

        if (enum_value == enum_values.end()) {
            continue;
        }

        out << CS_INDENT << "    case " << enum_type << "." << EscapeCsIdentifier(enum_value->second) << ":\n";
        out << CS_INDENT << "        isDisabled = " << (prop->IsDisabled() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        isVirtual = " << (prop->IsVirtual() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        isDict = " << (prop->IsDict() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        isArray = " << (prop->IsArray() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        isStringLike = " << (prop->IsBaseTypeString() || prop->IsBaseTypeHash() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        enumName = \"" << EscapeCsStringLiteral(prop->IsBaseTypeEnum() ? prop->GetBaseTypeName() : "") << "\";\n";
        out << CS_INDENT << "        isInt = " << (prop->IsBaseTypeInt() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        isFloat = " << (prop->IsBaseTypeFloat() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        isBool = " << (prop->IsBaseTypeBool() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        baseSize = " << numeric_cast<int32_t>(prop->GetBaseSize()) << ";\n";
        out << CS_INDENT << "        isSynced = " << (prop->IsSynced() ? "true" : "false") << ";\n";
        out << CS_INDENT << "        return;\n";
    }

    out << CS_INDENT << "    default:\n";
    out << CS_INDENT << "        throw new ArgumentOutOfRangeException(nameof(property), property, \"Unknown property entry\");\n";
    out << CS_INDENT << "    }\n";
    out << CS_INDENT << "}\n\n";
}

static void AppendPropertyInfoAccessors(ostringstream& out, const EngineMetadata& meta)
{
    FO_STACK_TRACE_ENTRY();

    map<string, map<int32_t, string>> enum_values_by_index;

    for (const auto& [enum_name, enum_values] : MakeSortedEnums(meta)) {
        if (!enum_name.ends_with("Property")) {
            continue;
        }

        map<int32_t, string> values_by_index;

        for (const auto& [value_name, value] : enum_values) {
            values_by_index.emplace(value, value_name);
        }

        enum_values_by_index.emplace(enum_name, std::move(values_by_index));
    }

    out << "public static partial class Game\n";
    out << "{\n";

    for (const auto& [type_name, desc] : MakeSortedEntityTypes(meta.GetEntityTypes())) {
        auto enum_it = enum_values_by_index.find(strex("{}Property", type_name).str());

        if (!desc->PropRegistrar.as_nptr() || enum_it == enum_values_by_index.end()) {
            continue;
        }

        AppendPropertyInfoAccessor(out, type_name, desc->PropRegistrar.get(), enum_it->second);
    }

    for (const auto& [type_name, desc] : MakeSortedEntityTypes(meta.GetFixedTypes())) {
        auto enum_it = enum_values_by_index.find(strex("{}Property", type_name).str());

        if (!desc->PropRegistrar.as_nptr() || enum_it == enum_values_by_index.end()) {
            continue;
        }

        AppendPropertyInfoAccessor(out, type_name, desc->PropRegistrar.get(), enum_it->second);
    }

    out << "}\n\n";
}

