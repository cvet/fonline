static auto CollectManagedAssemblyFiles(const std::filesystem::path& dir) -> vector<std::filesystem::path>
{
    FO_STACK_TRACE_ENTRY();

    vector<std::filesystem::path> result;

    std::error_code ec;

    if (!std::filesystem::exists(dir, ec)) {
        if (ec) {
            throw ManagedScriptBakerException("Can't inspect Managed assemblies directory", dir.string());
        }

        return result;
    }

    for (std::filesystem::directory_iterator it(dir, ec); !ec && it != std::filesystem::directory_iterator(); it.increment(ec)) {
        if (!it->is_regular_file()) {
            continue;
        }
        if (it->path().extension() != ".dll") {
            continue;
        }

        result.emplace_back(it->path());
    }

    if (ec) {
        throw ManagedScriptBakerException("Can't enumerate Managed assemblies directory", dir.string());
    }

    std::ranges::sort(result, {}, [](const std::filesystem::path& path) { return path.filename().string(); });
    return result;
}

static void RemoveManagedOutputAssemblies(const std::filesystem::path& assemblies_output_dir, string_view target_name)
{
    FO_STACK_TRACE_ENTRY();

    auto output_dir = assemblies_output_dir / fs::make_path(strex("{}Assemblies", target_name));

    std::error_code ec;

    for (std::filesystem::directory_iterator it(output_dir, ec); !ec && it != std::filesystem::directory_iterator(); it.increment(ec)) {
        if (!it->is_regular_file()) {
            continue;
        }
        if (it->path().extension() != ".dll") {
            continue;
        }

        std::error_code remove_ec;
        std::filesystem::remove(it->path(), remove_ec);
    }

    if (ec) {
        std::error_code dir_ec;
        bool output_dir_exists = std::filesystem::is_directory(output_dir, dir_ec);

        if (output_dir_exists) {
            throw ManagedScriptBakerException("Can't enumerate Managed output assemblies", output_dir.string());
        }

        std::error_code create_ec;
        std::filesystem::create_directories(output_dir, create_ec);
    }
}

static void RemoveManagedBuildSidecars(const std::filesystem::path& assemblies_output_dir, string_view target_name, string_view assembly_file_name)
{
    FO_STACK_TRACE_ENTRY();

    auto output_dir = assemblies_output_dir / fs::make_path(strex("{}Assemblies", target_name));
    string assembly_file_stem = strex(assembly_file_name).erase_file_extension().str();

    std::error_code ec;
    std::filesystem::remove(output_dir / fs::make_path(strex("{}.deps.json", assembly_file_stem)), ec);
    ec.clear();
    std::filesystem::remove(output_dir / fs::make_path(strex("{}.pdb", assembly_file_stem)), ec);
}

static void AppendProjectReferences(std::ostream& file, const std::filesystem::path& project_dir, const vector<string>& references, optional<string_view> condition)
{
    FO_STACK_TRACE_ENTRY();

    if (references.empty()) {
        return;
    }

    file << "  <ItemGroup";

    if (condition.has_value()) {
        file << " Condition=\"" << EscapeXml(*condition) << "\"";
    }

    file << ">\n";

    for (const string& reference : references) {
        bool is_path_reference = reference.find('\\') != string::npos || reference.find('/') != string::npos || std::filesystem::path(fs::make_path(reference)).extension().string() == ".dll";

        if (is_path_reference) {
            std::filesystem::path reference_path = fs::make_path(reference);
            auto hint_path = reference_path.is_absolute() ? reference_path : std::filesystem::current_path() / reference_path;
            file << "    <Reference Include=\"" << EscapeXml(reference_path.stem().string()) << "\">\n";
            file << "      <HintPath>" << EscapeXml(MakeRelativeProjectPath(project_dir, hint_path)) << "</HintPath>\n";
            file << "    </Reference>\n";
        }
        else {
            file << "    <Reference Include=\"" << EscapeXml(reference) << "\" />\n";
        }
    }

    file << "  </ItemGroup>\n";
}

